// Food picture map (design.md "Food art (Requirement 21)", "Food picture map").
// Pure data, no React. Keys are food keys exactly as foods.ts makes them: plain
// keys from groceryFoodKey, Foods page keys from foodKeyFor (including the
// allergen:<group> keys), the block-rule foods from blockRuleFoods(), and the
// extra forms foodKeyFromName makes from a built-in "Counts as" override
// (asparagu, couscou, ...), so a typed or pasted name finds the same picture.
//
// Lookup is by EXACT key only: word matching would show an egg for "egg
// noodle". A food gets its own picture only when the Fluent picture shows that
// same food, in any form; otherwise it gets its group picture (an empty jar or
// an empty bowl), which can never show a different food.

export type FoodGroup =
  | 'vegetable'
  | 'fruit'
  | 'grain'
  | 'protein'
  | 'dairy'
  | 'pantry'
  | 'other';

export interface FoodPictureEntry {
  group: FoodGroup;
  /** File name in public/art/foods/ without ".webp", e.g. 'carrot'. */
  picture?: string;
}

