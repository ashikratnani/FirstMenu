/** What a picture lookup returns: always a picture, plus the food's group. */
export interface FoodPicture {
  group: FoodGroup;
  picture: string;
  /** True when the picture is the food's own, false for a group picture. */
  own: boolean;
}

/**
 * The picture for a food key, by exact key. A key that is not in the map
 * (possible only for typed, pasted, shared or imported foods) gets the group
 * `other` and the generic bowl.
 */
export function pictureFor(key: string, map: Record<string, FoodPictureEntry> = FOOD_PICTURES): FoodPicture {
  const entry = Object.prototype.hasOwnProperty.call(map, key) ? map[key] : undefined;
  if (!entry) return { group: 'other', picture: GROUP_PICTURES.other, own: false };
  if (entry.picture) return { group: entry.group, picture: entry.picture, own: true };
  return { group: entry.group, picture: GROUP_PICTURES[entry.group], own: false };
}
