//    is pending pr-reviewer sign-off (docs/recipe-sources.md). Pages were
//    fetched on RETRIEVED. Ingredients and quantities are copied from the page;
//    steps are reworded and keep the source's method, times and temperatures.
//  - Salt, sugar, brown sugar, honey or bouillon that the screen blocks are left
//    out and recorded in source.adaptations, but only where the screen blocks
//    them at the youngest age of a tagged stage. A recipe tagged 24-36 only
//    keeps every source ingredient (the screen blocks salt, sugar and honey only
//    under 24 months); recipes.test.ts lists the ones that keep a blocked item.
//  - Salty sauces and seasonings the screen has no term for (teriyaki sauce,
//    taco seasoning mix, canned broth, canned cream soup, bottled dressing) take
//    the stricter stage: those recipes are tagged 24-36 only and keep them.
//  - Recipes with nut pieces (sliced or chopped nuts, even optional ones) are
//    tagged 24-36 only: the screen's whole-nuts reminder applies below that and
//    no source page describes grinding the nuts. Raw, firm vegetables (celery,
//    cucumber slices, radishes) are tagged 24-36 only as well.
//  - Servings are the source's own count when it states one. Otherwise they are
//    an estimate (yield divided by a stated portion, or the count of pieces the
//    directions make), disclosed in source.adaptations and pinned in
//    recipes.test.ts.
//  - Stage tags follow texture (design rule 4). A recipe is tagged 6-8 only when
//    it is smooth or soft enough to mash, and then serveAs lists puree or mashed.
//  - Hand washing and produce rinsing lines on the source pages are not
//    repeated. The refrigerate-within-2-hours line is kept in the last step.
//  - No `storage` is set: none of these pages gives fridge or freezer days.
//  - Near-duplicates were checked against every earlier batch and the simple
//    ideas; where two source pages made nearly the same dish (fruit and yogurt
//    layers, banana and yogurt, apple and nut butter) only one was kept.
//
