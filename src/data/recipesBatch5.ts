// Rules followed (design.md "Built-in recipe expansion" and "Recipe source
// criteria", plus the v1 sourcing rules), the same as batch 4:
//  - Every recipe comes from a published page of an approved publisher: Food
//    Hero (Oregon State University Extension), the Institute of Child Nutrition
//    Child Nutrition Recipe Box (USDA, family child care home or ages 3-5
//    six-serving versions) or, new in this batch, Oregon Sea Grant (Oregon State
