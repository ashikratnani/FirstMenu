//    State University Extension) or the Institute of Child Nutrition Child
//    Nutrition Recipe Box (USDA, six-serving versions). Pages were fetched on
//    RETRIEVED. Ingredients and quantities are copied from the page; steps are
//    reworded and keep the source's method, times, temperatures and tips.
//  - An ingredient the screen blocks is left out (and recorded in
//    source.adaptations) only when the screen blocks it at every stage the
//    recipe is tagged with. A recipe that keeps salt, sugar, honey or maple
//    syrup is tagged 24-36 only; a recipe that leaves salt out is tagged with
//    stages under 24 months only.
//  - Salty sauces and seasonings the screen has no term for (broth, jarred
//    sauce, salsa, taco seasoning, lemon pepper, cured ham or bacon bits),
//    sweetened products (flavored yogurt, fruit in syrup, juice concentrate),
//    raw or lightly cooked firm vegetables, whole hard shells and whole
//    kernels or grapes take the stricter stage.
//  - Stage tags follow texture (design rule 4). A recipe is tagged 6-8 only
//    when the page itself says to blend, puree or mash it, and then serveAs
//    lists puree or mashed and the recipe is not tagged for toddlers.
//  - Servings are the source's own count when it states one. Where the page
//    gives a yield in cups, servings are an estimate disclosed in
//    source.adaptations.
//  - Hand washing and produce rinsing lines on the source pages are not
//    repeated.
//  - Where a page lists a choice ("chopped onion or onion powder"), one option
//    is used and the adaptation says which.
//  - Near-duplicates were checked against every earlier batch by dish, not only
//    by ingredient keys.
//
