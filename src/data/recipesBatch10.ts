// Built-in recipes, batch 10 (task 14.3, Requirement 14). Pure data, no React.
//
// Priority of this batch: the biggest gaps to the 500 goal after batch 9
// (12-23 Easy, 24-36 Easy and the soy allergen group first). The unused UNL
// Food and Food Hero pages are mostly near-duplicates of earlier recipes or use
// salt, sugar, broth or a jarred sauce, so this batch also draws on the
// Minnesota WIC and Texas WIC pages that earlier batches left unused (23 and 4
// recipes). Many recipes are tagged 24-36 only (everything the page lists is
// kept) and the rest leave salt or sugar out and are tagged 12-23 only. Soy
// gets 16 recipes (soy sauce, tofu), all 24-36 only where a soy sauce is kept.
// Easy stays thin because an Easy recipe has at most 5 required ingredients,
// at most 4 steps and no oven, and the unused pages that fit are duplicates.
//
// Rules followed (design.md "Built-in recipe expansion" and "Recipe source
// criteria", plus the v1 sourcing rules), the same as batches 4 to 9:
//  - Every recipe comes from a published page of a publisher listed in
//    docs/recipe-sources.md: UNL Food (Nebraska Extension), Food Hero (Oregon
//    State University Extension), Texas WIC or Minnesota WIC. Pages were
//    fetched on RETRIEVED. Ingredients and quantities are copied from the page; steps are
//    reworded and keep the source's method, times, temperatures and tips.
//  - An ingredient the screen blocks is left out (and recorded in
//    source.adaptations) only when the screen blocks it at every stage the
//    recipe is tagged with. A recipe that keeps salt, sugar, honey or maple
//    syrup is tagged 24-36 only; a recipe that leaves salt out is tagged with
//    stages under 24 months only.
//  - Salty sauces and seasonings the screen has no term for (broth, jarred
//    sauce, salsa, taco seasoning, lemon pepper, cured ham or bacon bits),
//    sweetened products (flavored yogurt, fruit in syrup, juice concentrate),
//    raw or lightly cooked firm vegetables, whole hard shells and whole
//    kernels or grapes take the stricter stage.
//  - Stage tags follow texture (design rule 4). A recipe is tagged 6-8 only
//    when the page itself says to blend, puree or mash it, and then serveAs
//    lists puree or mashed and the recipe is not tagged for toddlers.
//  - Servings are the source's own count when it states one. Where the page
//    gives a yield in cups, servings are an estimate disclosed in
//    source.adaptations.
//  - Hand washing and produce rinsing lines on the source pages are not
//    repeated.
//  - Where a page lists a choice ("chopped onion or onion powder"), one option
//    is used and the adaptation says which.
//  - Near-duplicates were checked against every earlier batch by dish, not only
//    by ingredient keys.
//
// This file must not import from ./recipes (recipes.ts imports it).

